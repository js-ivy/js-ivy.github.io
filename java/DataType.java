/**
 * Określa typ danych, który powinien być przechowywany
 * jako jedyna wartość w obiekcie produkowanym przez maszynę.
 */
public enum DataType {

    /** Liczba całkowita typu Integer. */
    INTEGER,

    /** Liczba zmiennoprzecinkowa typu Double. */
    DOUBLE,

    /** Pojedynczy znak typu Character. */
    CHARACTER,

    /** Napis typu String. */
    STRING
}