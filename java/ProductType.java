/**
 * Określa rodzaj podzespołu składanego przez linię montażową.
 */
public enum ProductType {

    /** Jednostka napędowa: dwa koła zębate i jedna sprężyna. */
    DRIVE_UNIT,

    /** Jednostka sterująca: jedno koło zębate i dwa kryształy. */
    CONTROL_UNIT,

    /** Stabilizator: jedna sprężyna i jeden kryształ. */
    STABILIZER
}
